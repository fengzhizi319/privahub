// BreakGlassMethod tags audit events written by the offline admin CLI.
const BreakGlassMethod = "break_glass_cli"

// BreakGlassResetRequest is an offline (CLI) administrator password reset.
type BreakGlassResetRequest struct {
	UserName string
	// NewPassword is the plaintext one-time password (generated by the CLI).
	NewPassword string
	// Reason is mandatory and recorded in the audit trail (ticket id, why).
	Reason string
	// Operator identifies the person running the tool (OS user, --operator).
	Operator string
	// Host is the machine / pod the tool ran on (audit attribute).
	Host string
	Now  time.Time
}

// BreakGlassResetPassword stores NewPassword with the server KDF, flags the
// account must_change_password, clears login / reset lockouts, revokes every
// session (user_tokens rows + password version bump) and appends a system
// audit event — all in one transaction, so the reset never happens without
// its audit record.
func BreakGlassResetPassword(ctx context.Context, db *gorm.DB, req BreakGlassResetRequest) error {
	if db == nil {
		return errors.New("nil db")
	}
	name := strings.TrimSpace(req.UserName)
	reason := strings.TrimSpace(req.Reason)
	switch {
	case name == "":
		return errors.New("user name is required")
	case reason == "":
		return errors.New("a reason is required (it is recorded in the audit trail)")
	case req.NewPassword == "":
		return errors.New("new password is required")
	}
	now := req.Now
	if now.IsZero() {
		now = time.Now()
	}
	return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		var user model.UserAccountsDO
		if err := tx.Where("name = ?", name).Take(&user).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return fmt.Errorf("%w: %s", ErrUserNotFound, name)
			}
			return err
		}
		updates, err := newPasswordUpdates(&user, HashPassword(req.NewPassword), true, now)
		if err != nil {
			return err
		}
		for _, col := range []string{"failed_attempts", "locked_invalid_time", "passwd_reset_failed_attempts", "gmt_passwd_reset_release"} {
			updates[col] = nil
		}
		if err := tx.Model(&model.UserAccountsDO{}).Where("id = ?", user.ID).Updates(updates).Error; err != nil {
			return err
		}
		if err := ClearUserSessions(ctx, tx, user.Name); err != nil {
			return err
		}
		operator := strings.TrimSpace(req.Operator)
		if operator == "" {
			operator = "unknown"
		}
		_, err = audit.NewStore(tx).AppendEvents(ctx, audit.Event{
			Time:         now,
			Actor:        "privahub-admin",
			ActorType:    audit.ActorSystem,
			OwnerID:      user.OwnerID,
			Action:       audit.ActionPasswordReset,
			ResourceType: "user",
			ResourceID:   user.Name,
			Result:       audit.ResultSuccess,
			Reason:       reason,
			Extra: map[string]string{
				"method":   BreakGlassMethod,
				"operator": operator,
				"host":     req.Host,
			},
		})
		if err != nil {
			return fmt.Errorf("audit record: %w", err)
		}
		return nil
	})
}
